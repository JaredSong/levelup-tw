import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { ANNOUNCED_OUTSIDE_CATALOG } from './wdaCatalog.mjs'

function occupationCode(manifest) {
  return manifest.sections.find((section) => section.sourceGroup === 'occupation')?.subjectCode
}

// A 「最新版」 claim older than this is no longer evidence: rebuild after
// `npm run refresh:official-catalog` to restore it.
const OFFICIAL_CHECK_MAX_AGE_DAYS = 45

export function officialCheckedDate(official, now = new Date()) {
  if (!official?.generatedAt || !official.installedDrift?.ok) return null
  const checked = new Date(official.generatedAt)
  if ((now - checked) / 86_400_000 > OFFICIAL_CHECK_MAX_AGE_DAYS) return null
  // Calendar date in Taiwan, where the claim is read.
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Taipei' }).format(checked)
}

// Packs listed in ANNOUNCED_OUTSIDE_CATALOG (wdaCatalog.mjs) that don't carry
// the announced file yet stay out of the announced-year claim.
function missingAnnouncedSources(manifests) {
  const byId = new Map(manifests.map((manifest) => [manifest.examId, manifest]))
  return new Set(ANNOUNCED_OUTSIDE_CATALOG.filter((change) => {
    const manifest = byId.get(change.examId)
    return manifest && !(manifest.sources ?? []).some((source) => source.subjectCode === change.subjectCode && source.pdfFilename === change.pdfFilename)
  }).map((change) => change.examId))
}

/**
 * Per pack, when the check found it on banks announced for a later exam day:
 * examId → that day, if every source is on the announced version; examId →
 * null if only some are (half old, half new — no 「最新版」 claim either way).
 * Packs absent from the map are entirely on today's versions.
 */
export function officialUpcoming(official, now = new Date(), manifests = []) {
  if (!officialCheckedDate(official, now)) return {}
  const behind = new Set([...(official.installedDrift.behindAnnounced ?? []).map((entry) => entry.examId), ...missingAnnouncedSources(manifests)])
  const byExam = {}
  for (const entry of official.installedDrift.upcoming ?? []) {
    byExam[entry.examId] = behind.has(entry.examId) ? null : entry.effectiveFrom
  }
  return Object.fromEntries(Object.entries(byExam).sort())
}

export function buildLandingCatalog(manifests, demand, featuredCount = 4, official = null) {
  const demandByKey = new Map(demand.ranking.map((entry) => [`${entry.code}:${entry.level}`, entry]))
  const ranked = manifests.map((manifest) => {
    const code = occupationCode(manifest)
    const stats = demandByKey.get(`${code}:${manifest.level}`)
    return {
      examId: manifest.examId,
      titleZh: manifest.titleZh,
      code,
      level: manifest.level,
      applicantCount: stats?.applicantCount ?? null,
    }
  }).sort((a, b) => (
    (b.applicantCount ?? -1) - (a.applicantCount ?? -1)
    || a.titleZh.localeCompare(b.titleZh, 'zh-Hant-TW')
  ))
  const featured = ranked.slice(0, featuredCount)
  const featuredNames = featured.map((entry) => entry.titleZh).join('、')
  return {
    generatedAt: new Date().toISOString(),
    examCount: manifests.length,
    activeQuestionCount: manifests.reduce((total, manifest) => total + manifest.activeQuestionCount, 0),
    demandPeriod: demand.period,
    // Where the 報檢人次 figures come from, so any page quoting them can cite it.
    demandSource: demand.source,
    featuredExamIds: featured.map((entry) => entry.examId),
    exams: ranked,
    // Date every pack's source PDFs last matched the official current versions
    // byte for byte (source/wda-catalog.json; publicationGate fails the build on
    // drift). Pages say 「最新版」 only with this date, and only while it's fresh.
    officialCheckedDate: officialCheckedDate(official),
    // Packs already on banks the official site announced for a later exam day
    // (e.g. 116 banks during late 115): examId → the day they apply from.
    officialUpcoming: officialUpcoming(official, new Date(), manifests),
    metaDescription: `升級吧收錄 ${manifests.length} 種技術士技能檢定學科題庫，包括${featuredNames}。練官方公告題目、錯題複習與計時模擬考；免費、免註冊、可離線。`,
  }
}

async function main() {
  const root = new URL('../public/data/exams/', import.meta.url)
  const manifests = await Promise.all((await readdir(root)).map(async (directory) => (
    JSON.parse(await readFile(new URL(`${directory}/manifest.json`, root), 'utf8'))
  )))
  const demand = JSON.parse(await readFile(new URL('../source/wda-demand-ranking.json', import.meta.url), 'utf8'))
  const official = JSON.parse(await readFile(new URL('../source/wda-catalog.json', import.meta.url), 'utf8'))
  const catalog = buildLandingCatalog(manifests, demand, 4, official)
  await writeFile(new URL('../source/landing-catalog.json', import.meta.url), `${JSON.stringify(catalog, null, 2)}\n`)
  await writeFile(
    new URL('../src/app/generatedLandingCatalog.ts', import.meta.url),
    `// Generated by scripts/landingCatalog.mjs. Do not edit by hand.\nexport const GENERATED_LANDING_CATALOG = ${JSON.stringify(catalog, null, 2)} as const\n`,
  )
  if (!catalog.officialCheckedDate) console.warn('Landing: official-version check missing, failing or stale — pages will not claim 最新版')
  console.log(`Landing: ${catalog.examCount} exams; ${catalog.activeQuestionCount} active questions; featured ${catalog.featuredExamIds.join(', ')}`)
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === fileURLToPath(new URL(process.argv[1], `file://${process.cwd()}/`))
if (isMain) await main()
