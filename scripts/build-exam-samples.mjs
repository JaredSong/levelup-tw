// Generates src/app/generatedExamSamples.ts: for each published exam, a few
// text-only sample questions. The per-exam SEO pages (ExamPage) render these so
// each exam has unique, keyword-rich, crawlable content that matches "<考科> 題庫" search intent — without the page
// needing to fetch the full (large) question bank at runtime.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const EXAMS_DIR = new URL('../public/data/exams/', import.meta.url)
const OUT = new URL('../src/app/generatedExamSamples.ts', import.meta.url)
const SAMPLES_PER_EXAM = 6

function asArray(bank) {
  if (Array.isArray(bank)) return bank
  return bank.questions ?? Object.values(bank).find(Array.isArray) ?? []
}

/** Active, text-only, single-answer, fully-formed questions make the cleanest samples. */
function isCleanText(q) {
  return q.active !== false && !q.hasFigure && q.kind === 'single' && q.prompt && Array.isArray(q.options)
    && q.options.length >= 2 && Array.isArray(q.answers) && q.answers.length === 1
}

// Spread the samples across different work items rather than taking the first N
// from one section, so the page previews the breadth of the exam. Prefer the
// exam's own subject over shared 共同科目, and within it questions no other
// published bank also carries: sibling exams (中餐葷/素, 挖掘機/鏟裝機) share
// many prompts, and the same sample on both pages makes them near-duplicates.
function pickSamples(clean, isShared) {
  const tiers = [(q) => q.sourceGroup === 'occupation' && !isShared(q), (q) => q.sourceGroup === 'occupation', () => true]
  const chosen = []
  for (const tier of tiers) {
    const candidates = clean.filter((q) => tier(q) && !chosen.includes(q))
    const sections = new Set(chosen.map((q) => q.sectionTitle))
    for (const q of candidates) {
      if (chosen.length < SAMPLES_PER_EXAM && !sections.has(q.sectionTitle)) {
        chosen.push(q)
        sections.add(q.sectionTitle)
      }
    }
    for (const q of candidates) {
      if (chosen.length < SAMPLES_PER_EXAM && !chosen.includes(q)) chosen.push(q)
    }
  }
  return chosen.map((q) => ({
    id: q.id,
    sectionTitle: q.sectionTitle ?? '',
    prompt: q.prompt,
    options: q.options,
    answer: q.answers[0],
  }))
}

const banks = new Map()
for (const dir of readdirSync(EXAMS_DIR).sort()) {
  try {
    banks.set(dir, asArray(JSON.parse(readFileSync(new URL(`${dir}/questions.json`, EXAMS_DIR), 'utf8'))))
  } catch {
    continue
  }
}
// How many published banks carry each prompt (whitespace-insensitive).
const promptKey = (q) => String(q.prompt).replace(/\s+/g, '')
const banksWithPrompt = new Map()
for (const arr of banks.values()) {
  for (const key of new Set(arr.map(promptKey))) banksWithPrompt.set(key, (banksWithPrompt.get(key) ?? 0) + 1)
}

const out = {}
for (const [dir, arr] of banks) {
  out[dir] = { samples: pickSamples(arr.filter(isCleanText), (q) => banksWithPrompt.get(promptKey(q)) > 1) }
}

const header = `// Generated by scripts/build-exam-samples.mjs. Do not edit by hand.
export interface ExamSample {
  id: string
  sectionTitle: string
  prompt: string
  options: string[]
  /** 1-based index of the correct option. */
  answer: number
}
export interface ExamSampleSet {
  samples: ExamSample[]
}
export const GENERATED_EXAM_SAMPLES: Record<string, ExamSampleSet> = `
writeFileSync(OUT, `${header}${JSON.stringify(out, null, 2)}\n`)
console.log(`build-exam-samples: wrote ${Object.keys(out).length} exams to src/app/generatedExamSamples.ts`)
